//! The shared slugger (#18), used for file names here and heading ids later.
//! Letters stay letters in any script, lowercased; a URL percent-encodes
//! what isn't ASCII when it is written out.

use std::collections::HashMap;

/// github-slugger 2.0.0's `slug()`, exactly: lowercase, drop every character
/// its Unicode 13 regex matches, and turn each space into `-`.
/// `Foo Bar` → `foo-bar`, `C++` → `c`.
pub fn slug(text: &str) -> String {
    // `str::to_lowercase` matches JS `toLowerCase` here, final sigma and
    // `İ` → `i̇` included: both use the full, locale-free Unicode mapping.
    text.to_lowercase()
        .chars()
        .filter(|&c| !in_ranges(SLUG_REMOVED, c as u32))
        .map(|c| if c == ' ' { '-' } else { c })
        .collect()
}

/// Slugs unique within one document: github-slugger's `BananaSlug`.
#[derive(Debug, Default)]
pub struct Slugger {
    /// Every slug handed out, and for each original slug how many times it
    /// has been suffixed.
    occurrences: HashMap<String, usize>,
}

impl Slugger {
    /// github-slugger: a repeated slug gets `-1`, `-2`, …, skipping any
    /// suffixed slug that was itself handed out, so `x`, `x`, `x-1` give
    /// `x`, `x-1`, `x-1-1`.
    pub fn slug(&mut self, text: &str) -> String {
        let original = slug(text);
        let mut result = original.clone();
        while self.occurrences.contains_key(&result) {
            let count = self.occurrences.entry(original.clone()).or_default();
            *count += 1;
            result = format!("{original}-{count}");
        }
        self.occurrences.insert(result.clone(), 0);
        result
    }

    /// A heading's id as Astro 5 sets it (rehype-collect-headings in
    /// @astrojs/markdown-remark 6): github-slugger's unique slug, then one
    /// trailing `-` stripped, so `Ruskey 🦀` → `ruskey`. The strip comes after
    /// the dedupe and is Astro's, not github-slugger's: the slugger remembers
    /// `ruskey-`, so a later `Ruskey` heading also gets `ruskey`.
    pub fn heading_id(&mut self, text: &str) -> String {
        let mut id = self.slug(text);
        if id.ends_with('-') {
            id.pop();
        }
        id
    }
}

/// A Term's Slug (ADR 0005): the symbols that carry meaning are spelled out
/// first, so `C++` → `cplusplus` and `C#` → `csharp` instead of both `c`.
pub fn term_slug(term: &str) -> String {
    let term = term.trim();
    let spelled = match term.strip_prefix('.') {
        Some(rest) => format!("dot{rest}"),
        None => term.to_string(),
    };
    slug(&spelled.replace('+', "plus").replace('#', "sharp"))
}

/// Whether `s` is already a valid Slug: segments separated by `/`, each one
/// non-empty and unchanged by [`slug`].
pub fn is_valid(s: &str) -> bool {
    !s.is_empty() && s.split('/').all(|seg| !seg.is_empty() && slug(seg) == seg)
}

/// The Slug `s` most likely meant, for the fix on an invalid one.
pub fn corrected(s: &str) -> String {
    let segments: Vec<String> = s
        .split('/')
        .map(slug)
        .filter(|seg| !seg.is_empty())
        .collect();
    segments.join("/")
}

/// A URL path with everything outside unreserved ASCII and `/`
/// percent-encoded in uppercase, which every host tested serves without a
/// redirect (ADR 0005).
pub fn url_path(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for b in path.bytes() {
        if b.is_ascii_alphanumeric() || b"-_.~/".contains(&b) {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

/// Whether `c` falls in `table`, flat half-open ranges `[start, end)` sorted
/// ascending.
fn in_ranges(table: &[u32], c: u32) -> bool {
    table.partition_point(|&bound| bound <= c) % 2 == 1
}

